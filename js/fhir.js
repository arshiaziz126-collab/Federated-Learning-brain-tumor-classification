// HL7 FHIR R4 export - same resources and codes as backend/fhir.py.
const LOCAL_SYSTEM = "urn:neurofed-ai:codes";
const PSEUDONYM_SYSTEM = "urn:neurofed-ai:pseudonym";
const UCUM = "http://unitsofmeasure.org";
export const DISCLAIMER = "This system is a research prototype and is not a clinical diagnostic tool. It requires clinical validation before real-world medical use.";

const uuid = () => (crypto.randomUUID ? crypto.randomUUID()
  : "10000000-1000-4000-8000-100000000000".replace(/[018]/g, (c) => (c ^ (crypto.getRandomValues(new Uint8Array(1))[0] & (15 >> (c / 4)))).toString(16)));
const nowIso = () => new Date().toISOString().replace(/\.\d{3}Z$/, "+00:00");
const b64 = (s) => btoa(unescape(encodeURIComponent(s)));
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

export function buildBundle({ result, modelKind, modelInfo, pseudonym, reportHtml }) {
  const now = nowIso();
  const pid = uuid(), oid = uuid(), rid = uuid();
  const patient = {
    resourceType: "Patient", id: pid,
    identifier: [{ system: PSEUDONYM_SYSTEM, value: pseudonym || "anonymous" }],
    meta: { tag: [{ system: LOCAL_SYSTEM, code: "pseudonymised", display: "No directly identifying data" }] },
  };
  const components = Object.entries(result.probabilities).map(([name, p]) => ({
    code: { coding: [{ system: LOCAL_SYSTEM, code: `prob-${name}`, display: `Probability: ${name}` }], text: `Probability of ${name}` },
    valueQuantity: { value: Math.round(p * 10000) / 100, unit: "%", system: UCUM, code: "%" },
  }));
  const observation = {
    resourceType: "Observation", id: oid, status: "preliminary",
    category: [{ coding: [{ system: "http://terminology.hl7.org/CodeSystem/observation-category", code: "imaging", display: "Imaging" }] }],
    code: { coding: [{ system: LOCAL_SYSTEM, code: "ai-brain-tumour-class", display: "AI brain tumour classification" }],
            text: "AI-assisted brain tumour classification from MRI" },
    subject: { reference: `urn:uuid:${pid}` },
    effectiveDateTime: now, issued: now,
    valueCodeableConcept: { coding: [{ system: LOCAL_SYSTEM, code: result.predicted_class, display: result.predicted_class }], text: result.predicted_class },
    interpretation: [{ text: result.low_confidence ? "Low confidence" : "Confidence above threshold" }],
    method: { text: `${cap(modelKind)} CNN (NeuroFed AI)` },
    note: [{ text: "Generated by a research prototype. Not a clinical diagnosis." }],
    component: components,
  };
  const report = {
    resourceType: "DiagnosticReport", id: rid, status: "preliminary",
    category: [{ coding: [{ system: "http://terminology.hl7.org/CodeSystem/v2-0074", code: "RAD", display: "Radiology" }] }],
    code: { coding: [{ system: "http://loinc.org", code: "24590-2", display: "MR Brain" }], text: "MRI brain - AI-assisted screening (NeuroFed AI)" },
    subject: { reference: `urn:uuid:${pid}` },
    effectiveDateTime: now, issued: now,
    result: [{ reference: `urn:uuid:${oid}` }],
    conclusion: `AI model (${modelKind}) suggests '${result.predicted_class}' with ${(result.confidence * 100).toFixed(1)}% (uncalibrated) probability. Preliminary, AI-generated result for research use; requires review by a qualified clinician.`,
    extension: [{ url: "urn:neurofed-ai:model", valueString: JSON.stringify(modelInfo) }],
  };
  if (reportHtml) report.presentedForm = [{ contentType: "text/html", title: "NeuroFed AI screening report", data: b64(reportHtml) }];
  return {
    resourceType: "Bundle", id: uuid(), type: "collection", timestamp: now,
    entry: [patient, observation, report].map((r) => ({ fullUrl: `urn:uuid:${r.id}`, resource: r })),
  };
}

export function previewBundle(bundle) {
  return {
    ...bundle,
    entry: bundle.entry.map((e) => {
      const r = { ...e.resource };
      if (r.presentedForm) r.presentedForm = r.presentedForm.map((f) => ({ ...f, data: "<base64 HTML report omitted in preview>" }));
      if (r.extension) r.extension = r.extension.map((x) => ({ ...x, valueString: "<model details>" }));
      return { ...e, resource: r };
    }),
  };
}

const h = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

